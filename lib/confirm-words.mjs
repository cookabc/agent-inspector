/**
 * 确认串：整个工具只在这一处定义。
 *
 * 四条会改动磁盘的路径各要一个词，前端拿它做"输对才亮"的门控，
 * 服务端拿它做最后一道校验。**必须是同一个值** —— 两边各写一份，
 * 改一处忘另一处，界面就会放行一个服务端必然拒绝的请求。
 *
 * 词本身要说出"这一步在做什么"，而不是笼统的"确认"：
 * 用户在一屏里可能先后碰到几条不同的路径，同一个词会让人分不清
 * 刚才确认的是删除还是写入。
 *
 *   FILES          移入废纸篓之后还有退路，只有"彻底删除"这一档要确认
 *   SESSION        按行删会话 + VACUUM，不可撤销（有自动备份，但备份不是废纸篓）
 *   SESSION_ACTIVE 同上，且批次里**含还挂在应用主列表里的活跃会话** ——
 *                  删掉它们，下次打开那个应用历史就少几项。这个词比
 *                  SESSION 重，是为了让"删还在用的东西"不可能顺手点过去：
 *                  它必须单独敲一遍，不能靠上一次的肌肉记忆。
 *   RECOVER        往库里**写入**（加会话头与气泡）—— 这条不是删除，词也不同
 */
export const CONFIRM = Object.freeze({
  /** 文件彻底删除。 */
  FILES: '彻底删除',
  /** 按行清理历史会话（ZCode / Codex / Cursor）。 */
  SESSION: '清理',
  /** 批次里含活跃会话时的升级确认：删掉后应用主列表会少几项。 */
  SESSION_ACTIVE: '删除活跃会话',
  /** 把孤儿会话回灌进 Cursor 的库。 */
  RECOVER: '回灌',
});
